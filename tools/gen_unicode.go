// gen_unicode writes lib/unicode_tables.star: the Unicode properties the
// runtime needs to behave like starlark-go (which uses Go's unicode and
// strconv packages), taken from this Go toolchain's tables.
//
//	go run tools/gen_unicode.go > lib/unicode_tables.star
package main

import (
	"fmt"
	"os"
	"strings"
	"unicode"
)

// Class flags (CLASS_RANGES).
const (
	fLetter = 1 << iota
	fDigit
	fSpace
	fUpper
	fLower
	fTitle
	fCased // unicode.SimpleFold(r) != r
)

func list(name, doc string, xs []int, per int) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n%s = [\n", doc, name)
	for i := 0; i < len(xs); i += per {
		b.WriteString("   ")
		for _, x := range xs[i : i+per] {
			fmt.Fprintf(&b, " %d,", x)
		}
		b.WriteString("\n")
	}
	b.WriteString("]\n\n")
	return b.String()
}

func main() {
	out := os.Stdout
	fmt.Fprintf(out, "# lib/unicode_tables.star - generated by tools/gen_unicode.go from Go's\n")
	fmt.Fprintf(out, "# unicode package (Unicode %s). Do not edit.\n\n", unicode.Version)

	// strconv.IsPrint == unicode.IsPrint: ranges of printable runes >= 0x80
	var print []int
	for r := rune(0x80); r <= unicode.MaxRune; r++ {
		if unicode.IsPrint(r) {
			lo := r
			for r+1 <= unicode.MaxRune && unicode.IsPrint(r+1) {
				r++
			}
			print = append(print, int(lo), int(r))
		}
	}
	fmt.Fprint(out, list("PRINT_RANGES", "[lo, hi, ...]: runes >= 0x80 that strconv.Quote leaves unescaped", print, 2))

	flags := func(r rune) int {
		f := 0
		if unicode.IsLetter(r) {
			f |= fLetter
		}
		if unicode.IsDigit(r) {
			f |= fDigit
		}
		if unicode.IsSpace(r) {
			f |= fSpace
		}
		if unicode.IsUpper(r) {
			f |= fUpper
		}
		if unicode.IsLower(r) {
			f |= fLower
		}
		if unicode.IsTitle(r) {
			f |= fTitle
		}
		if unicode.SimpleFold(r) != r {
			f |= fCased
		}
		return f
	}
	var class []int
	for r := rune(0); r <= unicode.MaxRune; r++ {
		f := flags(r)
		if f == 0 {
			continue
		}
		lo := r
		for r+1 <= unicode.MaxRune && flags(r+1) == f {
			r++
		}
		class = append(class, int(lo), int(r), f)
	}
	fmt.Fprint(out, list("CLASS_RANGES", "[lo, hi, flags, ...]: 1 letter, 2 digit, 4 space, 8 upper, 16 lower, 32 title, 64 cased", class, 3))

	var cases []int
	for _, cr := range unicode.CaseRanges {
		cases = append(cases, int(cr.Lo), int(cr.Hi), int(cr.Delta[0]), int(cr.Delta[1]), int(cr.Delta[2]))
	}
	fmt.Fprint(out, list("CASE_RANGES", "[lo, hi, delta upper, delta lower, delta title, ...]: unicode.CaseRanges (delta 0x110000: alternating upper/lower)", cases, 5))
}
